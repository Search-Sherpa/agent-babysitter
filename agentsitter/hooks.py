"""Enforcement points outside the shell: git hooks and the agent-harness hook.

Git hooks are model-agnostic: whatever drives git, a commit, merge commit, push
or rebase needs a signed approval bound to the exact content. The agent-harness
hook speaks the JSON-on-stdin protocol (exit 0 allows, exit 2 blocks and shows
stderr to the agent) and covers shell commands, file edits and stopping.
"""

import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

from . import codes, config, gate, lanes, state as state_mod

HOOK_NAMES = ("pre-commit", "pre-merge-commit", "pre-push", "pre-rebase")
MARKER = "agentsitter hook"
# Releases before 0.2.0 were named agent-babysitter. Their hooks count as ours, so
# install-hooks replaces them without --force. Trust still needs the exact text.
MARKERS = (MARKER, "agent-babysitter hook")
PACKAGE_PARENT = Path(__file__).resolve().parent.parent
SHELL_TOOLS = {"Bash", "PowerShell"}
EDIT_TOOLS = {"Write", "Edit", "MultiEdit", "NotebookEdit"}
ENV_TEMPLATES = {"example", "sample", "template", "dist"}


class HookError(Exception):
    """Hooks cannot be installed as asked. Mapped to a usage error."""


# ---- installation ---------------------------------------------------------------

def hooks_dir(repo):
    done = subprocess.run(["git", "-C", str(repo), "rev-parse", "--git-path", "hooks"],
                          capture_output=True, text=True, timeout=30)
    if done.returncode != 0 or not done.stdout.strip():
        return None
    return Path(repo) / done.stdout.strip()


def _hook_text(repo, name):
    """The text of the hook git would run for this repository, or None."""
    directory = hooks_dir(repo)
    if directory is None:
        return None
    path = directory / name
    try:
        if not path.is_file():
            return None
        with open(path, encoding="utf-8", errors="replace", newline="") as handle:
            text = handle.read()
    except OSError:
        return None
    if os.name != "nt" and not os.access(path, os.X_OK):
        return None  # git skips a hook it cannot execute
    return text


def installed(repo, name):
    """True only when git would run exactly the hook this installation writes.

    A file that merely carries our marker proves nothing: the governed agent can
    write one, or point core.hooksPath at one. Callers rely on this to leave a
    git command to the hook, so the comparison is with the whole text.
    """
    return _hook_text(repo, name) == shim(name)


def stale(repo, name):
    """True when a hook of ours is there but is not the one this installation writes."""
    text = _hook_text(repo, name)
    return text is not None and any(m in text for m in MARKERS) and text != shim(name)


# The hook starts in the work tree, which the governed agent writes. -I keeps the
# current directory and every PYTHON* variable out of the import path. -S skips
# site-packages and its start-up files (.pth, sitecustomize), which sit in a
# virtual environment the agent may also write; this package needs only the
# standard library. The package itself is loaded from the one location recorded
# at install time.
SHIM_PROGRAM = (
    'import importlib.util as u, sys; '
    'd = sys.argv[1] + "/agentsitter"; '
    's = u.spec_from_file_location("agentsitter", d + "/__init__.py", submodule_search_locations=[d]); '
    'm = u.module_from_spec(s); sys.modules["agentsitter"] = m; s.loader.exec_module(m); '
    'from agentsitter.cli import main; '
    'sys.exit(main(["hook", "git", sys.argv[2]] + sys.argv[3:]))'
)


def shim(name, python=None, parent=None):
    """The hook script. The interpreter and package paths are data, never shell or Python source."""
    python = (python or sys.executable).replace("\\", "/")
    parent = (parent or str(PACKAGE_PARENT)).replace("\\", "/")
    return (
        "#!/bin/sh\n"
        f"# {MARKER} (generated by `agentsitter install-hooks`)\n"
        f"exec {shlex.quote(python)} -I -S -c {shlex.quote(SHIM_PROGRAM)} "
        f"{shlex.quote(parent)} {shlex.quote(name)} \"$@\"\n"
    )


def install(repo, force=False):
    """Write one shim per hook. Returns the paths written."""
    directory = hooks_dir(repo)
    if directory is None:
        raise HookError(f"{repo} is not a git repository")
    targets = [directory / name for name in HOOK_NAMES]
    if not force:
        foreign = [p for p in targets if p.exists() and not (installed(repo, p.name) or stale(repo, p.name))]
        if foreign:
            raise HookError("refusing to overwrite existing hooks not written by agentsitter: "
                            + ", ".join(p.name for p in foreign) + " (use --force to replace them)")
    directory.mkdir(parents=True, exist_ok=True)
    for path in targets:
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(shim(path.name))
        os.chmod(path, 0o755)
    return targets


# ---- git hooks --------------------------------------------------------------------

def _git(*args):
    """Plain git with the inherited env: git set GIT_DIR / GIT_INDEX_FILE for this hook."""
    done = subprocess.run(["git", *args], capture_output=True, text=True, timeout=60)
    return done.stdout.strip() if done.returncode == 0 else ""


def _merge_heads():
    """The commits a merge brings in. git writes MERGE_HEAD only after pre-merge-commit
    has run, so read the names `git merge` put in GIT_REFLOG_ACTION ("merge <commit>...")."""
    found = _git("rev-parse", "-q", "--verify", "MERGE_HEAD")
    if found:
        return found
    reflog_action = os.environ.get("GIT_REFLOG_ACTION", "")
    words = reflog_action.split()
    if len(words) > 1 and words[0] == "merge":
        heads = [_git("rev-parse", "-q", "--verify", f"{word}^{{commit}}") for word in words[1:]]
        if all(heads):
            return " ".join(heads)
    # Still bound to something stable, and visible to the approver as unresolved.
    return f"unresolved: {reflog_action}"


def _commit(name):
    """The commit a name points at now, or "" when it names none."""
    return _git("rev-parse", "--verify", "-q", name + "^{commit}") if name else ""


def _recorded_merge_heads():
    """Every commit named in MERGE_HEAD, or "" when no merge is being concluded."""
    path = _git("rev-parse", "--git-path", "MERGE_HEAD")
    try:
        return " ".join(Path(path).read_text(encoding="ascii", errors="replace").split()) if path else ""
    except OSError:
        return ""


def git_action(name, argv, stdin_text):
    """The exact action a git hook guards, or None when there is nothing to guard."""
    toplevel = _git("rev-parse", "--show-toplevel")
    repo = os.path.realpath(toplevel).replace("\\", "/")
    head = _git("rev-parse", "--verify", "-q", "HEAD")
    if name in ("pre-commit", "pre-merge-commit"):
        action = {"kind": "git-commit", "repo": repo, "tree": _git("write-tree"), "parent": head or "none"}
        if name == "pre-merge-commit":
            action["kind"] = "git-merge-commit"
            action["merge_head"] = _merge_heads()
        else:
            # `git commit` with MERGE_HEAD present concludes a merge: the other
            # parents are part of what is approved, not only the tree.
            others = _recorded_merge_heads()
            if others:
                action["merge_head"] = others
        return toplevel, action
    if name == "pre-push":
        updates = sorted(line.split() for line in (stdin_text or "").splitlines() if line.split())
        if not updates:
            return toplevel, None
        remote = argv[1] if len(argv) > 1 else (argv[0] if argv else "")
        return toplevel, {"kind": "git-push", "repo": repo, "remote": remote, "updates": updates}
    if name == "pre-rebase":
        branch = argv[1] if len(argv) > 1 else (_git("symbolic-ref", "--short", "-q", "HEAD") or "HEAD")
        upstream = argv[0] if argv else ""
        # Names can be pointed elsewhere after the approval; the commits they name cannot.
        return toplevel, {"kind": "git-rebase", "repo": repo, "upstream": upstream, "branch": branch,
                          "head": head, "upstream_commit": _commit(upstream), "branch_commit": _commit(branch)}
    raise HookError(f"unknown git hook {name!r}")


def git_hook(name, argv, stdin_text, cfg, env):
    from . import enforce

    toplevel, action = git_action(name, list(argv), stdin_text)
    if action is None:
        return codes.OK
    if not toplevel:
        print("agentsitter: cannot find the repository top level; blocking.", file=sys.stderr)
        return codes.APPROVAL_REQUIRED
    st = state_mod.for_project(toplevel, env)
    what = f"git {name.replace('pre-', '', 1)} ({action['kind']})"
    outcome = enforce.approval_outcome(st, action, cfg, env, True, 3, what)
    if outcome.code == codes.OK:
        return codes.OK
    print(f"agentsitter: blocked {what} in {action['repo']}.\n{outcome.message}\n"
          "Retry the same git command after approving. A human can bypass their own hooks "
          "with git's --no-verify.", file=sys.stderr)
    return outcome.code


# ---- the agent-harness hook --------------------------------------------------------

def _same(a, b):
    return os.path.normcase(os.path.realpath(str(a))) == os.path.normcase(os.path.realpath(str(b)))


def protected(path, cfg, env):
    """True when an edit to this absolute path could weaken governance or expose secrets.

    The path is judged as written and as it resolves, so a link to a protected
    file is as protected as the file.
    """
    resolved = os.path.realpath(path)
    return _protected(path, cfg, env) or (resolved != path and _protected(resolved, cfg, env))


def _protected(path, cfg, env):
    text = path.replace("\\", "/")
    lower = text.lower()
    name = lower.rsplit("/", 1)[-1]
    if name == ".env" or (name.startswith(".env.") and name[5:] not in ENV_TEMPLATES):
        return True
    if name == "allowed_signers" or "/.git/hooks/" in lower:
        return True
    padded = lower + "/"
    for folder in ("agentsitter", "agent-babysitter"):  # the second is the pre-0.2.0 name
        if f"/.config/{folder}/" in padded or f"/.local/state/{folder}/" in padded:
            return True
    if _same(path, config.config_path(env)) or _same(path, config.allowed_signers_path(cfg, env)):
        return True
    if any(re.search(pattern, text, re.IGNORECASE) for pattern in cfg["protected_paths"]):
        return True  # by default, the harness settings that install this hook
    if lanes._is_under(path, lanes.PACKAGE_DIR, strict=False):
        return True  # the code that is doing the enforcing
    return lanes._is_under(path, config.state_root(env), strict=False)


def agent_hook(stdin_text, cfg, env):
    from . import enforce

    try:
        payload = json.loads(stdin_text)
        if not isinstance(payload, dict):
            raise ValueError("payload is not a JSON object")
    except ValueError as exc:
        print(f"agentsitter: hook input is not valid JSON ({exc}); blocking.", file=sys.stderr)
        return 2
    cwd = payload.get("cwd") or os.getcwd()
    event = payload.get("hook_event_name")
    st = state_mod.for_project(lanes.project_root(cwd), env)

    if event == "PreToolUse":
        tool = payload.get("tool_name")
        tool_input = payload.get("tool_input") or {}
        if (tool in SHELL_TOOLS or tool in EDIT_TOOLS) and not isinstance(tool_input, dict):
            print(f"agentsitter: {tool} tool call with malformed input; blocking.", file=sys.stderr)
            return 2
        if tool in SHELL_TOOLS:
            command = tool_input.get("command")
            if not isinstance(command, str):
                print("agentsitter: shell tool call without a command; blocking.", file=sys.stderr)
                return 2
            outcome = enforce.check_command(command, cwd, cfg, env, st, mode="hook", consume=True)
            if outcome.code == codes.OK:
                return 0
            print(f"agentsitter: {outcome.message}", file=sys.stderr)
            return 2
        if tool in EDIT_TOOLS:
            targets = [tool_input[key] for key in ("file_path", "notebook_path") if key in tool_input]
            if not targets or not all(isinstance(target, str) and target for target in targets):
                # An edit we cannot place is not known to be harmless.
                print(f"agentsitter: {tool} tool call without a file path; blocking.", file=sys.stderr)
                return 2
            # Every path the call names is judged: which one the tool writes is the tool's business.
            paths = [os.path.normpath(os.path.join(cwd, os.path.expanduser(target))).replace("\\", "/")
                     for target in targets]
            guarded = [path for path in paths if protected(path, cfg, env)]
            if not guarded:
                return 0
            path = guarded[0]
            action = {"kind": "edit", "tool": tool, "path": path, "input_sha256": gate.detail_digest(tool_input)}
            outcome = enforce.approval_outcome(st, action, cfg, env, True, 3, f"{tool} of {path}",
                                               detail=tool_input)
            if outcome.code == codes.OK:
                return 0
            print(f"agentsitter: {outcome.message}", file=sys.stderr)
            return 2
        return 0

    if event == "Stop":
        if payload.get("stop_hook_active"):
            return 0
        outcome = enforce.checkpoint(cwd, cfg, env, st)
        if outcome.code == codes.CONSULT_REQUIRED:
            print(f"agentsitter: {outcome.message}", file=sys.stderr)
            return 2
        return 0
    return 0
